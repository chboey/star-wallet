import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import solc from "solc";

const root = resolve(import.meta.dirname, "..");
const sourceName = "simulation/ChildValidationProbe.sol";
const input = {
  language: "Solidity",
  sources: {
    [sourceName]: {
      content: await readFile(resolve(root, sourceName), "utf8"),
    },
  },
  settings: {
    optimizer: { enabled: true, runs: 500 },
    viaIR: true,
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.deployedBytecode.object"] } },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter(
  (error) => error.severity === "error",
);
if (errors.length)
  throw new Error(errors.map((error) => error.formattedMessage).join("\n"));
const probe = output.contracts[sourceName].ChildValidationProbe;
const abi = JSON.stringify(probe.abi, null, 2);
const code = JSON.stringify(`0x${probe.evm.deployedBytecode.object}`);
const header =
  "// Generated by scripts/compile-child-validation-probe.mjs. Simulation only; never deploy.\n";
await mkdir(resolve(root, "abi"), { recursive: true });
await writeFile(
  resolve(root, "abi/child-validation-probe.js"),
  `${header}export const childValidationProbeAbi = ${abi};\nexport const childValidationProbeCode = ${code};\n`,
);
await writeFile(
  resolve(root, "abi/child-validation-probe.d.ts"),
  `${header}export declare const childValidationProbeAbi: readonly ${abi};\nexport declare const childValidationProbeCode: ${code};\n`,
);
